//! Runtime-neutral, local workload-connector inspection.
//!
//! A host runtime transports these frames (Podman exec today, guest control in
//! a future VM backend). Neither this channel nor a self-signed report grants
//! tenant membership. Reports prove key possession; enrollment must additionally
//! verify owner-rooted authorization before using them as discovery seeds.

use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};

use crate::{EndpointRecord, IROH_ENDPOINT_ID_BYTES};

pub const CONNECTOR_CONTROL_VERSION: u16 = 2;
pub const MAX_CONNECTOR_FRAME_BYTES: usize = 64 * 1024;
pub const CONNECTOR_CHALLENGE_BYTES: usize = 32;
pub const DEFAULT_CONNECTOR_SOCKET: &str = "/var/run/podmesh/connector/control.sock";
pub const CONNECTOR_CONTROL_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(5);

/// Derive a fresh, domain-separated inspection challenge from the signed
/// owner command nonce. The nonce must be generated by the owner per request.
pub fn inspection_challenge(nonce: &str) -> [u8; CONNECTOR_CHALLENGE_BYTES] {
    blake3::derive_key(
        "podmesh/connector/inspection-challenge/v1",
        nonce.as_bytes(),
    )
}

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct ConnectorRequest {
    pub version: u16,
    pub challenge: [u8; CONNECTOR_CHALLENGE_BYTES],
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub install_identity: Option<crate::workload_identity::WorkloadIdentity>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seed_peer: Option<crate::service_discovery::ReplicaServiceRecord>,
}

impl ConnectorRequest {
    pub fn inspect(challenge: [u8; CONNECTOR_CHALLENGE_BYTES]) -> Self {
        Self {
            version: CONNECTOR_CONTROL_VERSION,
            challenge,
            install_identity: None,
            seed_peer: None,
        }
    }

    pub fn install(
        challenge: [u8; CONNECTOR_CHALLENGE_BYTES],
        identity: crate::workload_identity::WorkloadIdentity,
    ) -> Self {
        Self {
            version: CONNECTOR_CONTROL_VERSION,
            challenge,
            install_identity: Some(identity),
            seed_peer: None,
        }
    }

    pub fn seed(
        challenge: [u8; CONNECTOR_CHALLENGE_BYTES],
        record: crate::service_discovery::ReplicaServiceRecord,
    ) -> Self {
        Self {
            version: CONNECTOR_CONTROL_VERSION,
            challenge,
            install_identity: None,
            seed_peer: Some(record),
        }
    }
    pub fn validate(&self) -> Result<()> {
        ensure!(
            !(self.install_identity.is_some() && self.seed_peer.is_some()),
            "ambiguous connector mutation"
        );
        if let Some(record) = &self.seed_peer {
            record.to_bytes()?;
        }
        ensure!(
            self.version == CONNECTOR_CONTROL_VERSION,
            "unsupported connector request version"
        );
        if let Some(identity) = &self.install_identity {
            identity.to_bytes()?;
        }
        Ok(())
    }

    pub fn to_bytes(&self) -> Result<Vec<u8>> {
        self.validate()?;
        encode(self)
    }

    pub fn from_bytes(bytes: &[u8]) -> Result<Self> {
        let value: Self = decode(bytes)?;
        value.validate()?;
        Ok(value)
    }
}

/// Self-signed identity evidence, NOT an endpoint-bound tenant credential.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct ConnectorIdentityReport {
    pub owner_public_key_b64: String,
    pub workload_name: String,
    pub workload_id: String,
    pub manifest_id: String,
    pub replica_index: u32,
    pub replica_count: u32,
    pub challenge: [u8; CONNECTOR_CHALLENGE_BYTES],
    pub endpoint: EndpointRecord,
    pub credential_expires_at_secs: Option<u64>,
    pub credential: Option<crate::workload_identity::WorkloadIdentity>,
    pub service_record: Option<crate::service_discovery::ReplicaServiceRecord>,
    /// Signature by the Iroh transport key over the entire report, including
    /// the application-key-signed endpoint record and the fresh challenge.
    pub transport_signature: String,
}

impl ConnectorIdentityReport {
    fn canonical_bytes(&self) -> Result<Vec<u8>> {
        let mut report = self.clone();
        report.transport_signature.clear();
        Ok(postcard::to_allocvec(&report)?)
    }

    pub fn sign(mut self, transport_private: &[u8], now_secs: u64) -> Result<Self> {
        self.validate(now_secs)?;
        self.transport_signature = crypto::b64_encode(&crypto::sign_domain(
            transport_private,
            crypto::SignatureDomain::ConnectorIdentity,
            &self.canonical_bytes()?,
        )?);
        self.verify_signature(now_secs)?;
        Ok(self)
    }

    pub fn verify(
        &self,
        expected_owner: &str,
        expected_workload_id: &str,
        expected_challenge: &[u8; CONNECTOR_CHALLENGE_BYTES],
        now_secs: u64,
    ) -> Result<()> {
        ensure!(
            self.owner_public_key_b64 == expected_owner,
            "connector owner mismatch"
        );
        ensure!(
            self.workload_id == expected_workload_id,
            "connector workload mismatch"
        );
        ensure!(
            &self.challenge == expected_challenge,
            "connector challenge mismatch"
        );
        self.verify_signature(now_secs)
    }

    pub fn verify_signature(&self, now_secs: u64) -> Result<()> {
        self.validate(now_secs)?;
        let signature = crypto::b64_decode(&self.transport_signature)?;
        ensure!(signature.len() == 64, "invalid connector signature length");
        crypto::verify_domain(
            &self.endpoint.endpoint_id,
            crypto::SignatureDomain::ConnectorIdentity,
            &self.canonical_bytes()?,
            &signature,
        )
    }

    fn validate(&self, now_secs: u64) -> Result<()> {
        ensure!(
            !self.workload_name.is_empty() && self.workload_name.len() <= 253,
            "invalid connector workload name"
        );
        let owner = crypto::b64_decode(&self.owner_public_key_b64)?;
        ensure!(
            owner.len() == IROH_ENDPOINT_ID_BYTES,
            "invalid connector owner key"
        );
        ensure!(
            self.replica_count >= 1 && self.replica_count <= crate::MAX_WORKLOAD_REPLICAS,
            "invalid connector replica count"
        );
        ensure!(
            self.replica_index < self.replica_count,
            "invalid connector replica index"
        );
        ensure!(
            self.manifest_id == crate::route_id(&owner, &self.workload_name),
            "invalid connector routing identity"
        );
        ensure!(
            self.workload_id == crate::workload_id(&owner, &self.workload_name, self.replica_index),
            "invalid connector workload identity"
        );
        self.endpoint.verify(now_secs)?;
        if let Some(record) = &self.service_record {
            record.verify(&self.owner_public_key_b64, now_secs)?;
            ensure!(
                record.endpoint.endpoint_id == self.endpoint.endpoint_id
                    && record.endpoint.signing_pubkey == self.endpoint.signing_pubkey
                    && record.credential.delegation.scope.workload_id == self.workload_id,
                "connector service record mismatch"
            );
        }
        if let Some(credential) = &self.credential {
            credential.verify(None)?;
            let endpoint = self
                .endpoint
                .endpoint_id
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect::<String>();
            ensure!(
                credential.delegation.scope.tenant_owner == self.owner_public_key_b64
                    && credential.delegation.scope.manifest_id == self.manifest_id
                    && credential.delegation.scope.workload_id == self.workload_id
                    && credential.claims.endpoint_id == endpoint
                    && credential.claims.signing_public_key_b64 == self.endpoint.signing_pubkey,
                "connector credential binding mismatch"
            );
            ensure!(
                self.credential_expires_at_secs == Some(credential.claims.expires_at_secs),
                "connector credential expiry mismatch"
            );
        } else {
            ensure!(
                self.credential_expires_at_secs.is_none(),
                "connector expiry has no credential proof"
            );
        }
        Ok(())
    }
}

#[derive(Clone, Copy, Debug, Serialize, Deserialize, PartialEq, Eq)]
pub enum ConnectorError {
    Unavailable,
    Unsupported,
    Rejected,
}

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct ConnectorResponse {
    pub version: u16,
    pub identity: Option<ConnectorIdentityReport>,
    pub error: Option<ConnectorError>,
}

impl ConnectorResponse {
    pub fn identity(identity: ConnectorIdentityReport) -> Self {
        Self {
            version: CONNECTOR_CONTROL_VERSION,
            identity: Some(identity),
            error: None,
        }
    }

    pub fn error(error: ConnectorError) -> Self {
        Self {
            version: CONNECTOR_CONTROL_VERSION,
            identity: None,
            error: Some(error),
        }
    }

    pub fn validate(&self) -> Result<()> {
        ensure!(
            self.version == CONNECTOR_CONTROL_VERSION,
            "unsupported connector response version"
        );
        ensure!(
            self.identity.is_some() != self.error.is_some(),
            "ambiguous connector response"
        );
        Ok(())
    }

    pub fn to_bytes(&self) -> Result<Vec<u8>> {
        self.validate()?;
        encode(self)
    }

    pub fn from_bytes(bytes: &[u8]) -> Result<Self> {
        let value: Self = decode(bytes)?;
        value.validate()?;
        Ok(value)
    }
}

fn encode(value: &impl Serialize) -> Result<Vec<u8>> {
    let bytes = serde_json::to_vec(value)?;
    validate_size(bytes.len())?;
    Ok(bytes)
}

fn decode<T: serde::de::DeserializeOwned>(bytes: &[u8]) -> Result<T> {
    validate_size(bytes.len())?;
    serde_json::from_slice(bytes).context("decode connector frame")
}

pub fn validate_size(size: usize) -> Result<()> {
    ensure!(
        size > 0 && size <= MAX_CONNECTOR_FRAME_BYTES,
        "invalid connector frame size"
    );
    Ok(())
}

/// Length-prefixed local frames share the same bound on every runtime transport.
pub async fn read_frame(reader: &mut (impl tokio::io::AsyncRead + Unpin)) -> Result<Vec<u8>> {
    use tokio::io::AsyncReadExt;
    let size = reader.read_u32().await? as usize;
    validate_size(size)?;
    let mut bytes = vec![0; size];
    reader.read_exact(&mut bytes).await?;
    Ok(bytes)
}

pub async fn write_frame(
    writer: &mut (impl tokio::io::AsyncWrite + Unpin),
    bytes: &[u8],
) -> Result<()> {
    use tokio::io::AsyncWriteExt;
    validate_size(bytes.len())?;
    writer.write_u32(bytes.len() as u32).await?;
    writer.write_all(bytes).await?;
    writer.flush().await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const NOW: u64 = 1_800_000_000;

    proptest::proptest! {
        #[test]
        fn request_roundtrips_arbitrary_challenges(challenge in proptest::arbitrary::any::<[u8; CONNECTOR_CHALLENGE_BYTES]>()) {
            let request = ConnectorRequest::inspect(challenge);
            let bytes = request.to_bytes().unwrap();
            proptest::prop_assert!(bytes.len() <= MAX_CONNECTOR_FRAME_BYTES);
            proptest::prop_assert_eq!(ConnectorRequest::from_bytes(&bytes).unwrap(), request);
        }
    }

    fn report() -> ConnectorIdentityReport {
        let (owner, _) = crypto::generate_signing_keypair();
        let (transport_public, transport_private) = crypto::generate_signing_keypair();
        let (application_public, application_private) = crypto::generate_signing_keypair();
        ConnectorIdentityReport {
            owner_public_key_b64: crypto::b64_encode(&owner),
            workload_name: "demo".into(),
            workload_id: crate::workload_id(&owner, "demo", 1),
            manifest_id: crate::route_id(&owner, "demo"),
            replica_index: 1,
            replica_count: 3,
            challenge: [7; 32],
            endpoint: EndpointRecord {
                version: crate::ENDPOINT_RECORD_VERSION,
                endpoint_id: transport_public,
                relay_url: None,
                direct_addresses: vec!["127.0.0.1:1234".into()],
                signing_pubkey: String::new(),
                issued_at_secs: NOW,
                expires_at_secs: NOW + 300,
                signature: String::new(),
            }
            .sign(&application_public, &application_private, NOW)
            .unwrap(),
            credential_expires_at_secs: None,
            credential: None,
            service_record: None,
            transport_signature: String::new(),
        }
        .sign(&transport_private, NOW)
        .unwrap()
    }

    #[tokio::test]
    async fn wire_bound_is_checked_before_allocating_the_body() {
        use tokio::io::AsyncWriteExt;
        let (mut writer, mut reader) = tokio::io::duplex(32);
        writer
            .write_u32((MAX_CONNECTOR_FRAME_BYTES + 1) as u32)
            .await
            .unwrap();
        assert!(read_frame(&mut reader).await.is_err());
        let (mut writer, mut reader) = tokio::io::duplex(32);
        writer.write_u32(0).await.unwrap();
        assert!(read_frame(&mut reader).await.is_err());
        let (mut writer, mut reader) = tokio::io::duplex(32);
        write_frame(&mut writer, b"hello").await.unwrap();
        assert_eq!(read_frame(&mut reader).await.unwrap(), b"hello");
    }

    #[test]
    fn frames_are_bounded_strict_and_unambiguous() {
        let request = ConnectorRequest::inspect([1; 32]);
        assert_eq!(
            ConnectorRequest::from_bytes(&request.to_bytes().unwrap()).unwrap(),
            request
        );
        assert!(ConnectorRequest::from_bytes(&vec![b' '; MAX_CONNECTOR_FRAME_BYTES + 1]).is_err());
        assert!(ConnectorRequest::from_bytes(b"{}").is_err());
        let mut bytes = request.to_bytes().unwrap();
        bytes.extend_from_slice(b"{}");
        assert!(ConnectorRequest::from_bytes(&bytes).is_err());
        let mut unknown: serde_json::Value =
            serde_json::from_slice(&request.to_bytes().unwrap()).unwrap();
        unknown["operation"] = serde_json::json!("execute");
        assert!(ConnectorRequest::from_bytes(&serde_json::to_vec(&unknown).unwrap()).is_err());
        assert!(
            ConnectorRequest {
                version: CONNECTOR_CONTROL_VERSION + 1,
                ..request
            }
            .to_bytes()
            .is_err()
        );
        let response = ConnectorResponse::identity(report());
        assert_eq!(
            ConnectorResponse::from_bytes(&response.to_bytes().unwrap()).unwrap(),
            response
        );
        assert!(
            ConnectorResponse {
                error: Some(ConnectorError::Rejected),
                ..response
            }
            .to_bytes()
            .is_err()
        );
    }

    #[test]
    fn report_proves_transport_possession_and_binds_application_identity() {
        let report = report();
        report
            .verify(
                &report.owner_public_key_b64,
                &report.workload_id,
                &[7; 32],
                NOW,
            )
            .unwrap();
        assert!(
            report
                .verify(
                    &report.owner_public_key_b64,
                    &report.workload_id,
                    &[8; 32],
                    NOW
                )
                .is_err()
        );
        assert!(
            report
                .verify("foreign-owner", &report.workload_id, &[7; 32], NOW)
                .is_err()
        );
        assert!(
            report
                .verify(
                    &report.owner_public_key_b64,
                    "foreign-workload",
                    &[7; 32],
                    NOW
                )
                .is_err()
        );
        assert!(report.verify_signature(NOW + 400).is_err());
        let mut tampered = report.clone();
        tampered.replica_index = 0;
        assert!(tampered.verify_signature(NOW).is_err());
        let mut tampered = report.clone();
        tampered.endpoint = self::report().endpoint;
        assert!(tampered.verify_signature(NOW).is_err());
        let mut tampered = report;
        tampered.challenge[0] ^= 1;
        assert!(tampered.verify_signature(NOW).is_err());
    }
}
